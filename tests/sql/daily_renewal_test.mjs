import { PGlite } from '@electric-sql/pglite';
import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
const db = new PGlite();
await db.exec('CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role BYPASSRLS;');
const baseline = readFileSync('db/migrations/0001_baseline.sql','utf8');
for (const table of ['users','app_settings']) {
  const start=baseline.indexOf(`CREATE TABLE public.${table} (`);
  await db.exec(baseline.slice(start,baseline.indexOf('\n);',start)+3));
}
const migration = readFileSync('db/migrations/20261026235246_daily_renewal_notifications.sql','utf8');
await db.exec(migration.split('-- SCHEDULER:')[0]);
await db.exec(readFileSync('db/migrations/20261027001007_daily_renewal_delivery_revision.sql','utf8'));
const scalar = async(sql,args=[]) => (await db.query(sql,args)).rows[0]?.v;
const rpc = async(name,args=[]) => scalar(`select public.${name}(${args.map((_,i)=>'$'+(i+1)).join(',')}) as v`,args);
const today = await scalar("select (now() at time zone 'Asia/Damascus')::date::text as v");
await db.exec("insert into public.app_settings(key,value) values ('daily_renewal_points',50);");
await db.exec(`insert into public.users(user_id,username,first_name,free_points,paid_points,last_renewal,joined_at)
 select i,'student'||i,'طالب',7,80,(now() at time zone 'Asia/Damascus')::date-1,now()-interval '2 days' from generate_series(1,6) i;
 update public.users set renewal_notifications=false where user_id=2;
 update public.users set bot_delivery_state='blocked' where user_id=3;
 update public.users set last_renewal=(now() at time zone 'Asia/Damascus')::date,free_points=13 where user_id=4;`);
assert.equal(await rpc('daily_renewal_begin'),null,'no immediate broadcast at deployment');
assert.equal(Number(await scalar('select count(*) as v from public.daily_renewal_runs')),0);
await db.exec("update public.daily_renewal_config set start_day=(now() at time zone 'Asia/Damascus')::date;");
await rpc('daily_renewal_begin');
assert.equal(Number(await scalar('select free_points as v from public.users where user_id=1')),50);
assert.equal(Number(await scalar('select paid_points as v from public.users where user_id=1')),80);
assert.equal(Number(await scalar('select free_points as v from public.users where user_id=2')),50,'opt-out still renews');
assert.equal(Number(await scalar('select free_points as v from public.users where user_id=3')),50,'blocked still renews');
assert.equal(Number(await scalar('select free_points as v from public.users where user_id=4')),13,'lazy renewal never refills twice');
assert.equal(await scalar('select status as v from public.daily_renewal_deliveries where user_id=2'),'disabled');
assert.equal(await scalar('select status as v from public.daily_renewal_deliveries where user_id=3'),'excluded');
await db.exec('update public.users set free_points=3 where user_id=1');
await rpc('daily_renewal_begin');
assert.equal(Number(await scalar('select free_points as v from public.users where user_id=1')),3,'restart is idempotent');
await db.exec('update public.users set renewal_notifications=false where user_id=4');
let claim=await rpc('daily_renewal_claim');
assert.equal(claim.user_id,1);
assert.equal(await rpc('daily_renewal_report_claim'),null,'no premature report');
assert.equal(await rpc('daily_renewal_finish',[today,1,'00000000-0000-0000-0000-000000000000','sent','',0]),false);
assert.equal(await rpc('daily_renewal_finish',[today,1,claim.token,'pending','rate limit',60]),true);
assert.equal(await rpc('daily_renewal_claim'),null,'shared Telegram rate gate');
await db.exec("update public.daily_renewal_runs set not_before=now()-interval '1 second'");
claim=await rpc('daily_renewal_claim');
await rpc('daily_renewal_finish',[today,1,claim.token,'blocked','المستخدم حظر البوت',0]);
assert.equal(await scalar('select bot_delivery_state as v from public.users where user_id=1'),'blocked');
assert.equal(await rpc('daily_renewal_finish',[today,1,claim.token,'sent','',0]),false,'stale token cannot overwrite failure');
claim=await rpc('daily_renewal_claim');
assert.equal(claim.user_id,5,'opted-out after campaign start is skipped');
assert.equal(await scalar('select status as v from public.daily_renewal_deliveries where user_id=4'),'skipped');
await db.exec("update public.users set bot_delivery_state='reachable' where user_id=5;");
// Equal timestamps must not erase a newer membership event.
await db.exec("update public.users set bot_delivery_updated_at=(select claimed_at from public.daily_renewal_deliveries where user_id=5) where user_id=5");
await rpc('daily_renewal_finish',[today,5,claim.token,'blocked','old send failed',0]);
assert.equal(await scalar('select bot_delivery_state as v from public.users where user_id=5'),'reachable','newer incoming interaction wins');
claim=await rpc('daily_renewal_claim');
assert.equal(claim.user_id,6);
await db.exec("update public.daily_renewal_deliveries set claimed_at=now()-interval '3 minutes' where user_id=6");
assert.equal(await rpc('daily_renewal_claim'),null);
assert.equal(await scalar('select status as v from public.daily_renewal_deliveries where user_id=6'),'uncertain','crash never duplicates send');
assert.equal(await scalar("select user_snapshot->>'username' as v from public.daily_renewal_deliveries where user_id=1"),'student1');
const summary=await rpc('daily_renewal_summary',[today]);
assert.equal(summary.failed,2); assert.equal(summary.uncertain,1); assert.equal(summary.disabled,2); assert.equal(summary.excluded,1);
const report=await rpc('daily_renewal_report_claim');
assert.equal(report.day,today); assert.equal(await rpc('daily_renewal_report_claim'),null);
await rpc('daily_renewal_report_finish',[today,report.token,'sent',0]);
assert.equal(await rpc('daily_renewal_report_claim'),null);
assert.equal(await scalar("select has_function_privilege('anon','public.daily_renewal_begin()','EXECUTE') as v"),false);
assert.equal(await scalar("select has_table_privilege('anon','public.daily_renewal_deliveries','SELECT') as v"),false);
assert.equal(Number(await scalar("select count(*) as v from pg_class where relname in ('daily_renewal_config','daily_renewal_runs','daily_renewal_deliveries') and relrowsecurity")),3);
// Date changes at midnight in Damascus, independently of the database timezone.
assert.equal(await scalar("select ('2026-10-27 20:59:59+00'::timestamptz at time zone 'Asia/Damascus')::date::text as v"),'2026-10-27');
assert.equal(await scalar("select ('2026-10-27 21:00:00+00'::timestamptz at time zone 'Asia/Damascus')::date::text as v"),'2026-10-28');
await db.close();
console.log('Daily renewal SQL: balances, opt-outs, blocks, recovery, rate limits, reports, permissions and Damascus midnight passed.');
