CREATE OR REPLACE FUNCTION public.refund_user_points_split_atomic(target_user_id bigint, free_amount double precision, paid_amount double precision)
 RETURNS TABLE(free_points double precision, paid_points double precision)
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
BEGIN
  IF free_amount IS NULL OR free_amount < 0.0 OR paid_amount IS NULL OR paid_amount < 0.0 THEN
    RAISE EXCEPTION 'refund amounts must be non-negative';
  END IF;

  UPDATE public.users
  SET free_points = COALESCE(public.users.free_points, 0.0) + free_amount,
      paid_points = COALESCE(public.users.paid_points, 0.0) + paid_amount
  WHERE user_id = target_user_id;

  RETURN QUERY
  SELECT u.free_points, u.paid_points
  FROM public.users u
  WHERE u.user_id = target_user_id;
END;
$function$;

