CREATE OR REPLACE FUNCTION public.check_and_apply_daily_renewal_atomic(target_user_id bigint, today_date date, renewal_amount double precision DEFAULT NULL::double precision)
 RETURNS TABLE(free_points double precision, paid_points double precision, current_points double precision, renewal_status text)
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  target_user public.users%rowtype;
  effective_amount double precision;
begin
  select *
  into target_user
  from public.users
  where user_id = target_user_id
  for update;

  if not found then
    return;
  end if;

  if target_user.last_renewal is null
     or target_user.last_renewal < today_date then

    -- ترتيب الأولوية: جدول الإعدادات app_settings هو المصدر الأساسي
    -- (القابل للتعديل من لوحة الإدارة)، ثم القيمة الممرَّرة صراحة من الكود
    -- كاحتياط إن لم يوجد إعداد، ثم 50 كخط أمان أخير لو تعذّر كل ما سبق.
    effective_amount := coalesce(
      (select value from public.app_settings where key = 'daily_renewal_points'),
      renewal_amount,
      50.0
    );

    update public.users
    set free_points = effective_amount,
        last_renewal = today_date
    where user_id = target_user_id
    returning * into target_user;

    return query
    select
      target_user.free_points,
      target_user.paid_points,
      target_user.free_points + target_user.paid_points,
      'renewed'::text;
  else
    return query
    select
      target_user.free_points,
      target_user.paid_points,
      target_user.free_points + target_user.paid_points,
      'normal'::text;
  end if;
end;
$function$;

CREATE OR REPLACE FUNCTION public.deduct_user_points_atomic(target_user_id bigint, points_to_deduct double precision, questions_generated integer DEFAULT 0)
 RETURNS TABLE(remaining_points double precision, debited_free double precision, debited_paid double precision)
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE
  target_user public.users%ROWTYPE;
  v_from_free double precision;
  v_from_paid double precision;
  v_remaining double precision;
BEGIN
  IF points_to_deduct IS NULL OR points_to_deduct < 0.0 THEN
    RAISE EXCEPTION 'points_to_deduct must be non-negative';
  END IF;

  SELECT *
  INTO target_user
  FROM public.users
  WHERE user_id = target_user_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RETURN;
  END IF;

  IF COALESCE(target_user.free_points, 0.0)
     + COALESCE(target_user.paid_points, 0.0) < points_to_deduct THEN
    RETURN;
  END IF;

  v_from_free := LEAST(COALESCE(target_user.free_points, 0.0), points_to_deduct);
  v_from_paid := points_to_deduct - v_from_free;

  UPDATE public.users
  SET free_points = COALESCE(free_points, 0.0) - v_from_free,
      paid_points = COALESCE(paid_points, 0.0) - v_from_paid,
      total_questions = COALESCE(total_questions, 0)
                        + GREATEST(COALESCE(questions_generated, 0), 0)
  WHERE user_id = target_user_id
  RETURNING free_points + paid_points INTO v_remaining;

  RETURN QUERY SELECT v_remaining, v_from_free, v_from_paid;
END;
$function$;

