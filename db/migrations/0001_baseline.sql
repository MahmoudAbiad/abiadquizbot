CREATE OR REPLACE FUNCTION public.admin_add_points_atomic(target_user_id bigint, amount double precision, balance_type text DEFAULT 'paid'::text)
 RETURNS TABLE(free_points double precision, paid_points double precision, total_points double precision)
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
BEGIN
  IF balance_type NOT IN ('free', 'paid') THEN
    RAISE EXCEPTION 'balance_type must be free or paid';
  END IF;

  IF balance_type = 'free' THEN
    UPDATE public.users
    SET free_points = COALESCE(public.users.free_points, 0.0) + amount
    WHERE user_id = target_user_id;
  ELSE
    UPDATE public.users
    SET paid_points = COALESCE(public.users.paid_points, 0.0) + amount
    WHERE user_id = target_user_id;
  END IF;

  RETURN QUERY
  SELECT u.free_points, u.paid_points, u.free_points + u.paid_points
  FROM public.users u
  WHERE u.user_id = target_user_id;
END;
$function$;

CREATE OR REPLACE FUNCTION public.admin_join_stats(p_days integer)
 RETURNS TABLE(source text, cnt bigint)
 LANGUAGE sql
 STABLE
AS $function$
  SELECT COALESCE(join_source, 'unknown') AS source, COUNT(*)::bigint
  FROM public.users
  WHERE joined_at >= now() - make_interval(days => p_days)
  GROUP BY 1;
$function$;

CREATE OR REPLACE FUNCTION public.admin_joined_users(p_source text, p_days integer, p_limit integer DEFAULT 10, p_offset integer DEFAULT 0)
 RETURNS TABLE(user_id bigint, username text, first_name text, joined_at timestamp with time zone, detail text, total_count bigint)
 LANGUAGE sql
 STABLE
AS $function$
  SELECT u.user_id, u.username, u.first_name, u.joined_at,
         CASE u.join_source
           WHEN 'shared_link' THEN (SELECT q.source_title FROM public.quizzes q WHERE q.id = u.join_quiz_id)
           WHEN 'referral'    THEN (SELECT COALESCE('@' || NULLIF(r.username, 'Unknown'), r.first_name, r.user_id::text)
                                    FROM public.users r WHERE r.user_id = u.referred_by)
         END AS detail,
         COUNT(*) OVER() AS total_count
  FROM public.users u
  WHERE u.joined_at >= now() - make_interval(days => p_days)
    AND COALESCE(u.join_source, 'unknown') = p_source
  ORDER BY u.joined_at DESC
  LIMIT p_limit OFFSET p_offset;
$function$;

CREATE OR REPLACE FUNCTION public.admin_referrers_stats(p_days integer, p_limit integer DEFAULT 10, p_offset integer DEFAULT 0)
 RETURNS TABLE(referrer_id bigint, username text, first_name text, referred_count bigint, last_join timestamp with time zone, total_count bigint)
 LANGUAGE sql
 STABLE
AS $function$
  WITH g AS (
    SELECT referred_by AS rid, COUNT(*) AS c, MAX(joined_at) AS last_join
    FROM public.users
    WHERE referred_by IS NOT NULL
      AND joined_at >= now() - make_interval(days => p_days)
    GROUP BY 1
  )
  SELECT g.rid, r.username, r.first_name, g.c, g.last_join, COUNT(*) OVER()
  FROM g LEFT JOIN public.users r ON r.user_id = g.rid
  ORDER BY g.c DESC, g.last_join DESC
  LIMIT p_limit OFFSET p_offset;
$function$;

CREATE OR REPLACE FUNCTION public.admin_shared_links_stats(p_days integer, p_limit integer DEFAULT 5, p_offset integer DEFAULT 0)
 RETURNS TABLE(quiz_id uuid, title text, owner_id bigint, owner_name text, runs bigint, unique_runners bigint, joins bigint, total_count bigint)
 LANGUAGE sql
 STABLE
AS $function$
  WITH runs AS (
    SELECT a.quiz_id AS qid, COUNT(*) AS runs, COUNT(DISTINCT a.user_id) AS uniq
    FROM public.quiz_attempts a
    WHERE a.source_type = 'shared' AND a.quiz_id IS NOT NULL
      AND a.started_at >= now() - make_interval(days => p_days)
    GROUP BY 1
  ), joins AS (
    SELECT join_quiz_id AS qid, COUNT(*) AS joins
    FROM public.users
    WHERE join_source = 'shared_link' AND join_quiz_id IS NOT NULL
      AND joined_at >= now() - make_interval(days => p_days)
    GROUP BY 1
  ), merged AS (
    SELECT COALESCE(r.qid, j.qid) AS qid,
           COALESCE(r.runs, 0) AS runs, COALESCE(r.uniq, 0) AS uniq, COALESCE(j.joins, 0) AS joins
    FROM runs r FULL JOIN joins j ON j.qid = r.qid
  )
  SELECT q.id, q.source_title, q.creator_id,
         COALESCE('@' || NULLIF(o.username, 'Unknown'), o.first_name, q.creator_id::text),
         m.runs, m.uniq, m.joins, COUNT(*) OVER()
  FROM merged m
  JOIN public.quizzes q ON q.id = m.qid
  LEFT JOIN public.users o ON o.user_id = q.creator_id
  ORDER BY m.runs DESC, m.joins DESC, q.source_title
  LIMIT p_limit OFFSET p_offset;
$function$;

CREATE OR REPLACE FUNCTION public.ai_model_add(p_slot text, p_provider text, p_model_name text)
 RETURNS SETOF ai_model_slots
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_next_order integer;
begin
  if p_slot not in ('cascade', 'detection') then
    raise exception 'unknown slot: %', p_slot;
  end if;
  if p_provider not in ('gemini', 'groq', 'openai', 'vertex') then
    raise exception 'unknown provider: %', p_provider;
  end if;
  if p_model_name is null or length(trim(p_model_name)) = 0 then
    raise exception 'model_name is required';
  end if;

  select coalesce(max(display_order), 0) + 1 into v_next_order
  from public.ai_model_slots where slot = p_slot;

  return query
    insert into public.ai_model_slots (slot, provider, model_name, display_order, is_enabled)
    values (p_slot, p_provider, trim(p_model_name), v_next_order, true)
    returning *;
end;
$function$;

CREATE OR REPLACE FUNCTION public.ai_model_move(p_id bigint, p_direction text)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_slot text;
  v_order integer;
  v_neighbor_id bigint;
  v_neighbor_order integer;
begin
  if p_direction not in ('up', 'down') then
    raise exception 'unknown direction: %', p_direction;
  end if;

  select slot, display_order into v_slot, v_order
  from public.ai_model_slots where id = p_id;

  if not found then
    raise exception 'unknown ai_model_slots id: %', p_id;
  end if;

  if p_direction = 'up' then
    select id, display_order into v_neighbor_id, v_neighbor_order
    from public.ai_model_slots
    where slot = v_slot and display_order < v_order
    order by display_order desc limit 1;
  else
    select id, display_order into v_neighbor_id, v_neighbor_order
    from public.ai_model_slots
    where slot = v_slot and display_order > v_order
    order by display_order asc limit 1;
  end if;

  if v_neighbor_id is null then
    return; -- already at the edge, nothing to do
  end if;

  update public.ai_model_slots set display_order = v_neighbor_order, updated_at = now() where id = p_id;
  update public.ai_model_slots set display_order = v_order, updated_at = now() where id = v_neighbor_id;
end;
$function$;

