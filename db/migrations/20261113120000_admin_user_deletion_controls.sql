-- Migration: Admin user deletion controls (full wipe, keep quizzes, consent only, quizzes only)
BEGIN;

-- 1. Allow keeping quizzes when their creator user is deleted
ALTER TABLE public.quizzes
    ALTER COLUMN creator_id DROP NOT NULL;

ALTER TABLE public.quizzes
    DROP CONSTRAINT IF EXISTS quizzes_creator_id_fkey;

ALTER TABLE public.quizzes
    ADD CONSTRAINT quizzes_creator_id_fkey
    FOREIGN KEY (creator_id) REFERENCES public.users(user_id) ON DELETE SET NULL;

-- 2. Keep shared-links analytics resilient when a kept quiz has creator_id IS NULL
CREATE OR REPLACE FUNCTION public.admin_shared_links_stats(p_days integer, p_limit integer DEFAULT 5, p_offset integer DEFAULT 0)
 RETURNS TABLE(quiz_id uuid, title text, owner_id bigint, owner_name text, runs bigint, unique_runners bigint, joins bigint, total_count bigint)
 LANGUAGE sql
 STABLE
AS $function$
  WITH runs AS (
    SELECT a.quiz_id AS qid, COUNT(*) AS runs, COUNT(DISTINCT a.user_id) AS uniq
    FROM public.quiz_attempts a
    WHERE a.source_type = 'shared' AND a.quiz_id IS NOT NULL
      AND a.started_at >= now() - make_interval(days => p_days)
    GROUP BY 1
  ), joins AS (
    SELECT join_quiz_id AS qid, COUNT(*) AS joins
    FROM public.users
    WHERE join_source = 'shared_link' AND join_quiz_id IS NOT NULL
      AND joined_at >= now() - make_interval(days => p_days)
    GROUP BY 1
  ), merged AS (
    SELECT COALESCE(r.qid, j.qid) AS qid,
           COALESCE(r.runs, 0) AS runs, COALESCE(r.uniq, 0) AS uniq, COALESCE(j.joins, 0) AS joins
    FROM runs r FULL JOIN joins j ON j.qid = r.qid
  )
  SELECT q.id, q.source_title, q.creator_id,
         COALESCE('@' || NULLIF(o.username, 'Unknown'), o.first_name, q.creator_id::text, 'مستخدم محذوف'),
         m.runs, m.uniq, m.joins, COUNT(*) OVER()
  FROM merged m
  JOIN public.quizzes q ON q.id = m.qid
  LEFT JOIN public.users o ON o.user_id = q.creator_id
  ORDER BY m.runs DESC, m.joins DESC, q.source_title
  LIMIT p_limit OFFSET p_offset;
$function$;

-- 3. Atomic admin RPC for the 4 user deletion modes:
--    'full_wipe'    : delete user + all traces + consent + generated quizzes
--    'keep_quizzes' : delete user + all traces + consent, but keep generated quizzes (creator_id = NULL)
--    'consent_only' : delete user consent state & history only
--    'quizzes_only' : delete user's generated quizzes only
CREATE OR REPLACE FUNCTION public.admin_delete_user_action(p_user_id bigint, p_mode text)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
    v_user_existed boolean := false;
    v_consent_deleted boolean := false;
    v_deleted_quizzes_count integer := 0;
    v_kept_quizzes_count integer := 0;
    v_quiz_ids uuid[] := ARRAY[]::uuid[];
    v_file_hashes text[] := ARRAY[]::text[];
    v_orphan_hashes text[] := ARRAY[]::text[];
    v_match_ids uuid[] := ARRAY[]::uuid[];
BEGIN
    IF p_user_id IS NULL THEN
        RAISE EXCEPTION 'p_user_id is required';
    END IF;

    IF p_mode NOT IN ('full_wipe', 'keep_quizzes', 'consent_only', 'quizzes_only') THEN
        RAISE EXCEPTION 'invalid deletion mode: %', p_mode;
    END IF;

    SELECT EXISTS(SELECT 1 FROM public.users WHERE user_id = p_user_id)
      INTO v_user_existed;

    -- Mode 3: Consent only
    IF p_mode = 'consent_only' THEN
        DELETE FROM public.user_consent_events WHERE user_id = p_user_id;
        DELETE FROM public.user_consents WHERE user_id = p_user_id;
        v_consent_deleted := true;

        RETURN jsonb_build_object(
            'status', 'ok',
            'mode', p_mode,
            'user_existed', v_user_existed,
            'consent_deleted', v_consent_deleted,
            'deleted_quizzes_count', 0,
            'kept_quizzes_count', 0,
            'deleted_quiz_ids', '[]'::jsonb
        );
    END IF;

    -- Mode 4 or Mode 1: Delete quizzes generated by this user
    IF p_mode IN ('quizzes_only', 'full_wipe') THEN
        SELECT COALESCE(array_agg(id), ARRAY[]::uuid[]),
               COALESCE(array_agg(DISTINCT file_hash) FILTER (WHERE file_hash IS NOT NULL), ARRAY[]::text[])
          INTO v_quiz_ids, v_file_hashes
          FROM public.quizzes
         WHERE creator_id = p_user_id;

        v_deleted_quizzes_count := COALESCE(array_length(v_quiz_ids, 1), 0);

        IF v_deleted_quizzes_count > 0 THEN
            DELETE FROM public.quizzes WHERE id = ANY(v_quiz_ids);

            IF COALESCE(array_length(v_file_hashes, 1), 0) > 0 THEN
                SELECT COALESCE(array_agg(h), ARRAY[]::text[])
                  INTO v_orphan_hashes
                  FROM unnest(v_file_hashes) AS h
                 WHERE NOT EXISTS (
                     SELECT 1 FROM public.quizzes q WHERE q.file_hash = h
                 );

                IF COALESCE(array_length(v_orphan_hashes, 1), 0) > 0 THEN
                    DELETE FROM public.classification_votes WHERE file_hash = ANY(v_orphan_hashes);
                    DELETE FROM public.classification_locks WHERE file_hash = ANY(v_orphan_hashes);
                END IF;
            END IF;
        END IF;

        IF p_mode = 'quizzes_only' THEN
            RETURN jsonb_build_object(
                'status', 'ok',
                'mode', p_mode,
                'user_existed', v_user_existed,
                'consent_deleted', false,
                'deleted_quizzes_count', v_deleted_quizzes_count,
                'kept_quizzes_count', 0,
                'deleted_quiz_ids', to_jsonb(v_quiz_ids)
            );
        END IF;
    END IF;

    -- Mode 2: Detach generated quizzes so they remain in the central table
    IF p_mode = 'keep_quizzes' THEN
        UPDATE public.quizzes
           SET creator_id = NULL
         WHERE creator_id = p_user_id;
        GET DIAGNOSTICS v_kept_quizzes_count = ROW_COUNT;
    END IF;

    -- Full user & trace cleanup for 'full_wipe' and 'keep_quizzes'
    -- 1. Consent records
    DELETE FROM public.user_consent_events WHERE user_id = p_user_id;
    DELETE FROM public.user_consents WHERE user_id = p_user_id;
    v_consent_deleted := true;

    -- 2. Adjust likes/dislikes on remaining quizzes where this user voted, then delete votes
    WITH user_votes AS (
        DELETE FROM public.quiz_votes
         WHERE user_id = p_user_id
        RETURNING quiz_id, vote_type
    ),
    agg AS (
        SELECT quiz_id,
               COUNT(*) FILTER (WHERE vote_type = 'like') AS like_cnt,
               COUNT(*) FILTER (WHERE vote_type = 'dislike') AS dislike_cnt
          FROM user_votes
         GROUP BY quiz_id
    )
    UPDATE public.quizzes q
       SET likes = GREATEST(0, COALESCE(q.likes, 0) - agg.like_cnt),
           dislikes = GREATEST(0, COALESCE(q.dislikes, 0) - agg.dislike_cnt)
      FROM agg
     WHERE q.id = agg.quiz_id;

    -- 3. Challenge system tables (NO ACTION FKs require child-first cleanup)
    SELECT COALESCE(array_agg(id), ARRAY[]::uuid[])
      INTO v_match_ids
      FROM public.challenge_matches
     WHERE attacker_id = p_user_id OR defender_id = p_user_id;

    IF COALESCE(array_length(v_match_ids, 1), 0) > 0 THEN
        UPDATE public.challenge_live_queue
           SET match_id = NULL
         WHERE match_id = ANY(v_match_ids);

        DELETE FROM public.challenge_notifications WHERE match_id = ANY(v_match_ids);
        DELETE FROM public.challenge_events WHERE match_id = ANY(v_match_ids);
        DELETE FROM public.challenge_match_answers WHERE match_id = ANY(v_match_ids);
        DELETE FROM public.challenge_match_players WHERE match_id = ANY(v_match_ids);
        DELETE FROM public.challenge_matches WHERE id = ANY(v_match_ids);
    END IF;

    DELETE FROM public.challenge_live_queue WHERE user_id = p_user_id;
    DELETE FROM public.challenge_notifications WHERE user_id = p_user_id;
    DELETE FROM public.challenge_match_answers WHERE user_id = p_user_id;
    DELETE FROM public.challenge_match_players WHERE user_id = p_user_id;
    DELETE FROM public.challenge_towers WHERE user_id = p_user_id;
    DELETE FROM public.challenge_unit_stats WHERE user_id = p_user_id;
    DELETE FROM public.challenge_profiles WHERE user_id = p_user_id;

    -- 4. Non-cascading activity, logs, and operational tables
    DELETE FROM public.usage_events WHERE user_id = p_user_id;
    DELETE FROM public.ai_generation_log WHERE user_id = p_user_id;
    DELETE FROM public.classification_votes WHERE user_id = p_user_id;
    DELETE FROM public.daily_renewal_deliveries WHERE user_id = p_user_id;
    DELETE FROM public.gift_code_redemptions WHERE user_id = p_user_id;
    DELETE FROM public.admin_gift_recipients WHERE user_id = p_user_id;
    DELETE FROM public.payment_orders WHERE user_id = p_user_id;
    DELETE FROM public.group_quiz_answers WHERE user_id = p_user_id;
    DELETE FROM public.group_quiz_participants WHERE user_id = p_user_id;
    DELETE FROM public.quiz_attempts WHERE user_id = p_user_id;
    DELETE FROM public.logs WHERE user_id = p_user_id;

    -- 5. Nullable references in other tables
    UPDATE public.users SET referred_by = NULL WHERE referred_by = p_user_id;
    UPDATE public.runner_settings SET updated_by = NULL WHERE updated_by = p_user_id;
    UPDATE public.bot_chat_memberships SET added_by = NULL WHERE added_by = p_user_id;

    -- 6. Delete the user row (cascades to favorite_quizzes, favorite_quiz_sections,
    --    quiz_scores, quiz_feedbacks, quiz_responses, point_gifts, wallet_debits,
    --    runner_rounds, runner_tracks, runner_wallets, runner_mastery,
    --    runner_daily_study, group_quiz_sessions, export_profiles, archive.shared_quizzes)
    DELETE FROM public.users WHERE user_id = p_user_id;

    RETURN jsonb_build_object(
        'status', 'ok',
        'mode', p_mode,
        'user_existed', v_user_existed,
        'consent_deleted', v_consent_deleted,
        'deleted_quizzes_count', v_deleted_quizzes_count,
        'kept_quizzes_count', v_kept_quizzes_count,
        'deleted_quiz_ids', to_jsonb(v_quiz_ids)
    );
END;
$function$;

REVOKE ALL ON FUNCTION public.admin_delete_user_action(bigint, text) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.admin_delete_user_action(bigint, text) TO service_role;

COMMIT;
