-- Legal consent records, versioned document links, and private bot RPCs.
BEGIN;

CREATE TABLE IF NOT EXISTS public.legal_documents (
    document_type text NOT NULL CHECK (document_type IN ('terms', 'privacy')),
    version integer NOT NULL CHECK (version >= 1),
    title text NOT NULL,
    url text NOT NULL CHECK (url LIKE 'https://abiad.me/%'),
    source_updated_on date NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (document_type, version)
);

CREATE TABLE IF NOT EXISTS public.user_consents (
    user_id bigint PRIMARY KEY,
    status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'accepted', 'declined')),
    terms_version integer NOT NULL DEFAULT 0,
    privacy_version integer NOT NULL DEFAULT 0,
    first_prompted_at timestamptz NOT NULL DEFAULT now(),
    decided_at timestamptz,
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.user_consent_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    decision text NOT NULL CHECK (decision IN ('accepted', 'declined')),
    terms_version integer NOT NULL,
    privacy_version integer NOT NULL,
    decided_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.legal_documents ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.user_consents ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.user_consent_events ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Legal document links are publicly readable" ON public.legal_documents;
CREATE POLICY "Legal document links are publicly readable"
    ON public.legal_documents FOR SELECT TO anon, authenticated USING (true);

REVOKE ALL ON public.legal_documents, public.user_consents, public.user_consent_events FROM PUBLIC, anon, authenticated;
GRANT SELECT ON public.legal_documents TO anon, authenticated;
GRANT ALL ON public.legal_documents, public.user_consents, public.user_consent_events TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.user_consent_events_id_seq TO service_role;

INSERT INTO public.legal_documents(document_type, version, title, url, source_updated_on)
VALUES
 ('terms', 1, 'شروط الاستخدام', 'https://abiad.me/terms-of-service.html', DATE '2026-11-01'),
 ('privacy', 1, 'سياسة الخصوصية', 'https://abiad.me/privacy-policy.html', DATE '2026-11-01')
ON CONFLICT (document_type, version) DO UPDATE SET
 title = EXCLUDED.title, url = EXCLUDED.url, source_updated_on = EXCLUDED.source_updated_on;

INSERT INTO public.app_settings(key, value, label) VALUES
 ('terms_version', 1, 'نسخة شروط الاستخدام (ارفعها عند تعديل جوهري لطلب موافقة جديدة)'),
 ('privacy_version', 1, 'نسخة سياسة الخصوصية (ارفعها عند تعديل جوهري لطلب موافقة جديدة)')
ON CONFLICT (key) DO NOTHING;

CREATE OR REPLACE FUNCTION public.mark_consent_prompted(p_user_id bigint)
RETURNS void LANGUAGE sql SECURITY INVOKER SET search_path = '' AS $$
    INSERT INTO public.user_consents(user_id) VALUES (p_user_id)
    ON CONFLICT (user_id) DO NOTHING;
$$;

CREATE OR REPLACE FUNCTION public.record_consent(
    p_user_id bigint, p_decision text, p_terms_version integer, p_privacy_version integer
)
RETURNS jsonb LANGUAGE plpgsql SECURITY INVOKER SET search_path = '' AS $$
DECLARE cur public.user_consents%rowtype;
BEGIN
    IF p_decision NOT IN ('accepted', 'declined') THEN
        RAISE EXCEPTION 'invalid decision';
    END IF;
    IF p_terms_version < 1 OR p_privacy_version < 1 THEN
        RAISE EXCEPTION 'invalid version';
    END IF;

    INSERT INTO public.user_consents(user_id) VALUES (p_user_id)
    ON CONFLICT (user_id) DO NOTHING;
    SELECT * INTO cur FROM public.user_consents WHERE user_id = p_user_id FOR UPDATE;

    IF cur.status = p_decision
       AND cur.terms_version = p_terms_version
       AND cur.privacy_version = p_privacy_version THEN
        RETURN jsonb_build_object('changed', false, 'status', cur.status);
    END IF;

    UPDATE public.user_consents
       SET status = p_decision,
           terms_version = p_terms_version,
           privacy_version = p_privacy_version,
           decided_at = now(),
           updated_at = now()
     WHERE user_id = p_user_id;

    INSERT INTO public.user_consent_events(user_id, decision, terms_version, privacy_version)
    VALUES (p_user_id, p_decision, p_terms_version, p_privacy_version);

    RETURN jsonb_build_object('changed', true, 'status', p_decision);
END;
$$;

REVOKE ALL ON FUNCTION public.mark_consent_prompted(bigint) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.record_consent(bigint, text, integer, integer) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.mark_consent_prompted(bigint) TO service_role;
GRANT EXECUTE ON FUNCTION public.record_consent(bigint, text, integer, integer) TO service_role;

COMMIT;
